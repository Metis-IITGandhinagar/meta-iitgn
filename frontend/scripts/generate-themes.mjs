// Generates src/lib/daisyThemes.ts from daisyUI's built-in themes so the
// theme selector can never drift from the installed daisyUI version.
// Run with: npm run generate:themes
//
// The selector only exposes a small curated set of themes (see
// CURATED_THEME_IDS). daisyUI still ships every theme, so this script filters
// the built-in list down to the ones we actually want users to pick from.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import themes from "daisyui/theme/object.js";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const outPath = path.resolve(__dirname, "../src/lib/daisyThemes.ts");

// Single source of truth for which themes the UI offers. Keep this short and
// intentional: one neutral default, one dark, one light.
const CURATED_THEME_IDS = ["cupcake", "dark", "light"];

const data = themes.default ?? themes;
const available = Object.keys(data);

const missing = CURATED_THEME_IDS.filter((id) => !available.includes(id));
if (missing.length > 0) {
  throw new Error(
    `Curated theme(s) not found in installed daisyUI: ${missing.join(", ")}. ` +
      `Update CURATED_THEME_IDS in scripts/generate-themes.mjs.`
  );
}

const entries = CURATED_THEME_IDS.map((id) => [id, data[id]]);
const ids = entries.map(([id]) => id);
const darkIds = entries
  .filter(([, def]) => def["color-scheme"] === "dark")
  .map(([id]) => id);

const humanize = (id) =>
  id === "cmyk" ? "CMYK" : id.charAt(0).toUpperCase() + id.slice(1);

const wikiThemes = ids.map((id) => ({ id, label: humanize(id) }));

const file = `// AUTO-GENERATED by scripts/generate-themes.mjs — do not edit by hand.
// Source of truth: curated subset of daisyUI built-in themes
// (node_modules/daisyui/theme/object.js). See CURATED_THEME_IDS in
// scripts/generate-themes.mjs. Regenerate with: npm run generate:themes
/* eslint-disable */

export interface WikiTheme {
  id: string;
  label: string;
}

export const DAISY_THEME_IDS = ${JSON.stringify(ids)} as const;

export const DAISY_DARK_THEME_IDS = ${JSON.stringify(darkIds)} as const;

export const WIKI_THEMES: WikiTheme[] = ${JSON.stringify(wikiThemes, null, 2)};

export const DARK_THEMES: string[] = ${JSON.stringify(darkIds, null, 2)};
`;

fs.writeFileSync(outPath, file, "utf8");
console.log(
  `Generated src/lib/daisyThemes.ts — ${ids.length} themes (${darkIds.length} dark).`
);
